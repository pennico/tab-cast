package dk.pennico.tabcast.core

import org.json.JSONArray
import org.json.JSONObject
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File

/**
 * Replays browser recordings from jstest/out/NAME.json (made by jstest/catch.mjs on real pages) through the same
 * CatchSession + Prober code the app runs, and prints what the Cast list would show. Opt-in, needs the network:
 *   TABCAST_REPLAY=1 ./gradlew testDebugUnitTest --tests '*CatchReplayTest*' -i
 * Writes jstest/out/report.md. Fails if a recording marked as castable (jstest/expect.json) ends with no playable top
 * candidate.
 */
class CatchReplayTest {
    @Test fun replay() {
        assumeTrue(System.getenv("TABCAST_REPLAY") != null)
        val dir = File("../jstest/out")
        val files = dir.listFiles { f -> f.name.endsWith(".json") && f.name != "report.json" }?.sortedBy { it.name } ?: emptyList()
        assumeTrue(files.isNotEmpty())
        val expect = File("../jstest/expect.json").takeIf { it.exists() }?.let { JSONObject(it.readText()) } ?: JSONObject()
        val rules = SiteRules.parse(File("src/main/assets/site-rules.json").readText())
        val report = StringBuilder("# Catch replay report\n\nGenerated by CatchReplayTest from jstest/out recordings.\n\n")
        val failures = ArrayList<String>()
        for (f in files) {
            val rec = JSONObject(f.readText())
            val name = rec.getString("name")
            val pageUrl = rec.getString("pageUrl")
            // Probes send the recorded request headers but not the recording's cookies (on the tablet the app uses
            // the user's own WebView cookies; here there is no reason to replay a headless session's cookies).
            val cookieFor = { _: String -> null as String? }
            val s = CatchSession(pageUrl, SiteRules.forUrl(rules, pageUrl))
            // Interleave in recorded order: requests first is close enough (the app gets both concurrently).
            val reqs = rec.getJSONArray("requests")
            for (i in 0 until reqs.length()) {
                val r = reqs.getJSONObject(i)
                val h = r.getJSONObject("headers")
                s.onRequest(r.getString("url"), h.keys().asSequence().associateWith { h.getString(it) }, i.toLong())
            }
            val js = rec.getJSONArray("js")
            for (i in 0 until js.length()) JsEvent.parse(js.getString(i))?.let { s.onJs(it, 10_000L + i) }
            // Probe like the app: every stream/unknown candidate, a few files.
            for (c in s.ranked().take(8)) {
                if (c.kind.streaming || c.kind == Kind.UNKNOWN || c.kind.isVideoFile) {
                    s.updateInfo(c.url, Prober.probe(c.url, c.kind, c.headers, cookieFor))
                }
            }
            val ranked = s.ranked()
            report.append("## $name\n\n$pageUrl\n\n")
            report.append("- page title: ${s.pageTitle ?: "-"}; MSE: ${s.mseSeen}; playing seen: ${s.playingSeen}; iframes: ${s.iframes().size}\n")
            if (ranked.isEmpty()) report.append("- **nothing caught**\n")
            for ((i, c) in ranked.take(6).withIndex()) {
                report.append("${i + 1}. `${c.describe()}` via ${c.via}, score %.1f".format(c.score()))
                c.info?.error?.let { report.append(", error: $it") }
                report.append("\n   ${c.url.take(160)}\n")
            }
            report.append("\n")
            val top = ranked.firstOrNull()
            val ok = top != null && top.info?.error == null && (top.info?.httpStatus ?: 200) < 400 && top.info?.drm != true
            println("[$name] ${if (ok) "OK" else "NO PLAYABLE TOP"}: ${top?.describe()} ${top?.url?.take(120)}")
            if (expect.optBoolean(name, false) && !ok) failures += name
        }
        File(dir, "report.md").writeText(report.toString())
        if (failures.isNotEmpty()) throw AssertionError("no playable top candidate for: $failures (see jstest/out/report.md)")
    }

    private fun cookieHeader(cookies: JSONArray, url: String): String? {
        val host = Urls.host(url)
        val path = Urls.path(url)
        val https = url.startsWith("https")
        val parts = ArrayList<String>()
        for (i in 0 until cookies.length()) {
            val c = cookies.getJSONObject(i)
            val d = c.getString("domain").trimStart('.')
            if (!(host == d || host.endsWith(".$d"))) continue
            if (!path.startsWith(c.optString("path", "/"))) continue
            if (c.optBoolean("secure") && !https) continue
            parts += c.getString("name") + "=" + c.getString("value")
        }
        return parts.joinToString("; ").ifEmpty { null }
    }
}
